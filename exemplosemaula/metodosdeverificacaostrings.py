entrada = input("Digite alguma coisa: ")

print("É numerico?", entrada.isnumeric())
print("é alfabetico?", entrada.isalpha())
print("é alfanumerico?", entrada.isalnum())
print("é decimal?", entrada.isdecimal())
print("possui apenas espaços?", entrada.isspace())
print("esta em maiusculo?", entrada.isupper())
print("esta em minusculo?", entrada.islower())